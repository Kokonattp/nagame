"""Restaurant snapshot for cities the guide has no restaurant names for (owner's PC only).

Jev UltraFast drives a normal Chrome (separate profile, remote debugging): it dismisses
consent dialogs, scrolls, and decides when the restaurant list is showing. The names,
ratings, review counts and coordinates are then read from the page's own result links —
nothing is generated by a model. Search only: no sign-in, no booking, stops on CAPTCHA.

Run (PowerShell, from D:\\TT\\nagame):
  uv run --project D:\\TT\\nagame-workers\\jev-ultrafast --env-file .env.local python workers/eat-places/collect.py
  ... collect.py --cities Nagasaki,Kure      # only these, keep the rest
Output: data/places/eat-google.json
"""

import argparse
import json
import os
import re
import subprocess
import sys
import time
import urllib.request
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import quote_plus

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "data/places/eat-google.json"
CHROME = os.environ.get("CHROME_PATH", r"C:\Program Files\Google\Chrome\Application\chrome.exe")
PROFILE = os.environ.get("EAT_CHROME_PROFILE", r"D:\TT\nagame-workers\chrome-cdp-profile")
PORT = int(os.environ.get("EAT_CDP_PORT", "9224"))
GAP_S = 20  # between cities, like the flight collector
KEEP = 10  # restaurants per city

# Cities with no restaurant listing in the Wikivoyage guide (lib/tabi/cities.ts names).
# `q` is what Google Maps should search; a few need the area spelled out.
CITIES = {
    "Kushiro": "Kushiro Hokkaido", "Toya": "Lake Toya Hokkaido", "Sounkyo": "Sounkyo Onsen",
    "Towada": "Lake Towada", "Ginzan Onsen": "Ginzan Onsen Yamagata", "Tsuruoka": "Tsuruoka Yamagata",
    "Nozawa Onsen": "Nozawa Onsen", "Kurobe": "Unazuki Onsen Kurobe", "Wajima": "Wajima Ishikawa",
    "Gotemba": "Gotemba Shizuoka", "Amanohashidate": "Amanohashidate Miyazu", "Kinosaki": "Kinosaki Onsen",
    "Shirahama": "Shirahama Wakayama", "Nachikatsuura": "Kii-Katsuura Nachikatsuura", "Hongu": "Kumano Hongu Taisha area",
    "Asuka": "Asuka Nara", "Kure": "Kure Hiroshima", "Nagasaki": "Nagasaki", "Sasebo": "Sasebo Nagasaki",
    "Unzen": "Unzen Onsen", "Ureshino": "Ureshino Onsen Saga", "Kurokawa Onsen": "Kurokawa Onsen Kumamoto",
    "Zamami": "Zamami Island Okinawa",
}

GOAL = (
    "Show Google Maps search results for restaurants in {q}, Japan. If a consent or cookie dialog is open, "
    "close it without signing in. Stop as soon as a list of restaurants with star ratings is visible. "
    "Do not sign in, open a restaurant website, call, book, or share anything."
)

# Read the visible result list: each result is a link to /maps/place/… whose aria-label is the name.
READ = r"""(() => {
  const out = [];
  for (const a of document.querySelectorAll('a[href*="/maps/place/"]')) {
    const name = (a.getAttribute('aria-label') || '').trim();
    if (!name) continue;
    const card = a.closest('[role="article"]') || a.parentElement;
    const text = (card?.innerText || '').replace(/\s+/g, ' ');
    const rate = text.match(/(\d\.\d)\s*\(([\d,.]+)(K?)\)/);
    const coord = a.href.match(/!3d(-?\d+\.\d+)!4d(-?\d+\.\d+)/);
    // after "4.5(202)" Google prints "Seafood restaurant · ¥2,000–3,000 · address"
    const after = rate ? text.slice(text.indexOf(rate[0]) + rate[0].length).split('·').map(s => s.trim()) : [];
    const kind = after[0] && after[0].length < 40 ? after[0] : '';
    const price = (text.match(/¥[\d,]+\s*[–-]\s*[\d,]+|¥[\d,]+\+?/) || [''])[0];
    out.push({
      n: name,
      r: rate ? Number(rate[1]) : null,
      rc: rate ? Math.round(Number(rate[2].replace(/,/g, '')) * (rate[3] ? 1000 : 1)) : null,
      la: coord ? Number(coord[1]) : null,
      lo: coord ? Number(coord[2]) : null,
      cat: kind,
      price,
      url: a.href.split('?')[0],
    });
  }
  return { url: location.href, blocked: /\/sorry\/|unusual traffic|recaptcha/i.test(location.href + document.body.innerText.slice(0, 3000)), rows: out };
})()"""

SCROLL_FEED = "(() => { const f = document.querySelector('[role=\"feed\"]'); if (f) f.scrollBy(0, 2400); return !!f; })()"


def start_chrome():
    """A normal Chrome with its own profile and remote debugging (nothing faked)."""
    try:
        urllib.request.urlopen(f"http://127.0.0.1:{PORT}/json/version", timeout=2)
        return None  # already running
    except OSError:
        pass
    proc = subprocess.Popen([CHROME, f"--remote-debugging-port={PORT}", f"--user-data-dir={PROFILE}", "--no-first-run", "about:blank"])
    for _ in range(50):
        try:
            urllib.request.urlopen(f"http://127.0.0.1:{PORT}/json/version", timeout=2)
            return proc
        except OSError:
            time.sleep(0.2)
    raise SystemExit("Chrome did not open its debugging port")


def rank(rows):
    """Well-rated places that enough people reviewed; one entry per name."""
    seen, good = set(), []
    for r in rows:
        if r["n"] in seen or r["r"] is None or (r["rc"] or 0) < 20 or r["la"] is None:
            continue
        seen.add(r["n"])
        good.append(r)
    # rating pulled toward 4.0 until ~100 people have reviewed it, so 5.0 from 20 reviews does not win
    good.sort(key=lambda r: (r["r"] * r["rc"] + 4.0 * 100) / (r["rc"] + 100), reverse=True)
    return good[:KEEP]


def collect_city(Agent, city, q):
    url = f"https://www.google.com/maps/search/{quote_plus('restaurants in ' + q)}?hl=en"
    agent = Agent(url, GOAL.format(q=q))
    try:
        steps = 0
        for state in agent.run():
            steps = len(state["history"])
        status = agent.state["status"]
        page = agent.browser.evaluate(READ)
        if page["blocked"]:
            return {"blocked": True}
        # load a second screenful of results so the ranking has more to choose from
        if agent.browser.evaluate(SCROLL_FEED):
            time.sleep(2.0)
            page = agent.browser.evaluate(READ)
        return {"status": status, "steps": steps, "seen": len(page["rows"]), "rows": rank(page["rows"])}
    finally:
        agent.close()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cities", help="comma-separated subset; others are kept from the last run")
    args = ap.parse_args()
    wanted = [c.strip() for c in args.cities.split(",")] if args.cities else list(CITIES)
    unknown = [c for c in wanted if c not in CITIES]
    if unknown:
        raise SystemExit(f"Unknown city: {', '.join(unknown)}")

    os.environ.setdefault("BU_CDP_URL", f"http://127.0.0.1:{PORT}")
    os.environ.setdefault("BU_NAME", "nagame-eat")
    chrome = start_chrome()
    from jev_ultrafast import Agent  # after BU_CDP_URL is set, so the harness attaches to our Chrome

    old = json.loads(OUT.read_text(encoding="utf-8")) if OUT.exists() else {"cities": {}}
    cities = dict(old.get("cities", {}))
    try:
        for i, city in enumerate(wanted):
            if i:
                time.sleep(GAP_S)
            t0 = time.monotonic()
            try:
                res = collect_city(Agent, city, CITIES[city])
            except Exception as e:  # one city failing keeps the others
                print(f"{city}: failed ({e})", flush=True)
                continue
            if res.get("blocked"):
                print(f"{city}: Google showed a block/CAPTCHA page — stopping, previous data kept", flush=True)
                break
            print(f"{city}: {res['status']} in {res['steps']} actions, {res['seen']} seen, kept {len(res['rows'])} ({time.monotonic() - t0:.0f}s)", flush=True)
            if res["rows"]:
                cities[city] = res["rows"]
    finally:
        OUT.write_text(json.dumps({
            "checkedAt": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "source": "Google Maps search results, read on the owner's PC (Jev UltraFast + normal Chrome)",
            "cities": cities,
        }, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}: {len(cities)} cities", flush=True)
        if chrome:
            chrome.terminate()


if __name__ == "__main__":
    sys.exit(main())
